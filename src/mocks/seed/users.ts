/** The password of every demo account, and the code every demo message or authenticator "sends". */
export const DEMO_PASSWORD = 'Demo@1234';
export const DEMO_CODE = '123456';

/** An account in the mock backend. Passwords are kept in plain text: this is sample data in memory. */
export interface UserSeed {
  id: string;
  fullName: string;
  phone: string;
  email?: string;
  preferredLanguage: Language;
  roles: RoleAssignment[];
  password: string;
  phoneVerified: boolean;
  emailConfirmed: boolean;
  mfaEnrolled: boolean;
  recoveryCodes: string[];
  failedSignIns: number;
  lockedUntil?: string;
  /** A TOTP key generated by `startEnrollment` and not confirmed yet. */
  pendingMfaSecret?: string;
  pendingRecoveryCodes?: string[];
  /** Listed on the demo sign-in screen with this label when set. */
  demoLabel?: Role | 'Applicant';
}

const org = (role: Role): RoleAssignment => ({ role, scope: 'Organization' });
const at = (role: Role, ...branchIds: string[]): RoleAssignment => ({ role, scope: 'Branch', branchIds });

const DEMO_RECOVERY_CODES = ['4821-7730', '9156-0284', '3307-6619', '7742-1058', '5590-3846', '1263-9471', '8034-5512', '6618-2097'];

type Person = Pick<UserSeed, 'id' | 'fullName' | 'phone' | 'roles'> & Partial<UserSeed>;

/** A verified account with the demo password; staff have their authenticator set up. */
export const account = (person: Person): UserSeed => ({
  preferredLanguage: 'ar',
  password: DEMO_PASSWORD,
  phoneVerified: true,
  emailConfirmed: !!person.email,
  mfaEnrolled: true,
  recoveryCodes: person.roles.some((r) => r.role !== 'Patient') ? [...DEMO_RECOVERY_CODES] : [],
  failedSignIns: 0,
  ...person,
});

